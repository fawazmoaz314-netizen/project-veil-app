using Veil.Domain.Conversations;
using Veil.Domain.Users;

namespace Veil.Domain.Messages;

public class Message
{
    public Guid Id { get; set; }

    /// <summary>
    /// Database-generated, strictly increasing number. Gives a stable total
    /// order for pagination and lets reconnecting clients ask for
    /// "everything after sequence N" to recover missed messages.
    /// </summary>
    public long Sequence { get; set; }

    public Guid ConversationId { get; set; }

    public Conversation Conversation { get; set; } = null!;

    /// <summary>Always taken from the authenticated user, never from the request body.</summary>
    public Guid SenderId { get; set; }

    public AppUser Sender { get; set; } = null!;

    /// <summary>
    /// Idempotency key generated by the client. (SenderId, ClientMessageId) is
    /// unique, so retrying a send after a network failure never duplicates it.
    /// </summary>
    public Guid ClientMessageId { get; set; }

    public string ContentType { get; set; } = MessageContentTypes.Text;

    public string Body { get; set; } = string.Empty;

    public DateTime CreatedAtUtc { get; set; }
}

public static class MessageContentTypes
{
    public const string Text = "text/plain";

    // Future: attachments, end-to-end encrypted envelopes, etc.
    public static readonly IReadOnlySet<string> Allowed = new HashSet<string>(StringComparer.Ordinal) { Text };
}
